let currentLang: Lang = 'zh-CN'

export function getLang (): Lang { return currentLang }
export function setCurrentLang (l: Lang) { currentLang = l }

export function translate (key: string, lang: Lang, params?: Record<string, string | number>): string {
  const entry = DICT[key]
  let s = entry ? (entry[lang] ?? entry.zh) : key
  if (params) s = s.replace(/\{(\w+)\}/g, (_, k) => String(params[k] ?? ''))
  return s
}

// t() for plain modules (useMock / useStore / useFormat / useApi); reads the
// module-level language kept in sync by useLang. Components use useLang().t()
// instead so templates re-render on toggle.
export function t (key: string, params?: Record<string, string | number>): string {
  return translate(key, currentLang, params)
}
